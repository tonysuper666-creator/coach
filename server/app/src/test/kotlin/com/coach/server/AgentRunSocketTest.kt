class AgentRunSocketTest {
    @Test fun ledgerFramesDoNotRevokeAgentRunCapability(): Unit = runBlocking {
        val received = CompletableDeferred<String>()
        val engine = embeddedServer(Netty, host="127.0.0.1", port=0) {
            install(WebSockets)
            routing { webSocketRaw("/v1/ws") {
                send(Frame.Text("""{"epoch":"synthetic","lastSeq":1,"agentRunsSupported":true}"""))
                // Both the HTTP catch-up hint and streamed ledger carry epoch, but are not hellos.
                send(Frame.Text("""{"t":"ledger","course":"course","epoch":"synthetic","events":[],"httpCatchUp":{"after":0,"throughSeq":1}}"""))
                send(Frame.Text("""{"t":"ledger","course":"course","epoch":"synthetic","events":[]}"""))
                send(Frame.Text("""{"t":"msg.snapshot","msg":"sentinel","threadId":"observed","i":1,"text":"SYNTHETIC ONLY","status":"complete"}"""))
                for (frame in incoming) when (frame) {
                    is Frame.Ping -> send(Frame.Pong(frame.data))
                    is Frame.Text -> received.complete(frame.readText())
                    else -> Unit
                }
            } }
        }.apply { start(wait=false) }
        val scope = CoroutineScope(SupervisorJob()+Dispatchers.Default)
        val model = TutorModel(System::currentTimeMillis)
        val client = TutorClient("http://127.0.0.1:${engine.engine.resolvedConnectors().first().port}",
            "device","t".repeat(43),model,agentRunId="oppo")
        try {
            client.start(scope)
            withTimeout(5_000) {
                while (!model.state.value.connected || model.state.value.threads["observed"]?.items?.isEmpty() != false) delay(20)
            }
            assertTrue(client.open(agentThreadId("oppo","thread"),"course","kp",emptyList(),"SYNTHETIC ONLY"),
                "A ledger update must not disable a supported agent connection")
            assertTrue(withTimeout(5_000) { received.await() }.contains("tutor.open"))
        } finally { client.close();scope.cancel();engine.stop(0,200) }
    }

    @Test fun agentCanOpenTutorAfterExistingCourseCatchUp(): Unit = runBlocking {
        val root = Files.createTempDirectory("coach-agent-catchup-")
        val scope = CoroutineScope(SupervisorJob()+Dispatchers.Default)
        val token = "synthetic-agent-catchup-token-32-characters"
        val store = LedgerStore(root).also { it.enroll("phone",token) }
        store.append("course","note_saved",json("noteId" to "note","text" to "SYNTHETIC ONLY"))
        val actor = LedgerActor(scope,store)
        val engine = embeddedServer(Netty,host="127.0.0.1",port=0) {
            ledgerRoutes(actor,MutableSharedFlow(extraBufferCapacity=8),ChatService(actor,scope))
        }.apply { start(false) }
        val thread = agentThreadId("oppo","thread")
        val client = TutorClient("http://127.0.0.1:${engine.engine.resolvedConnectors().single().port}",
            "phone",token,TutorModel(System::currentTimeMillis),agentRunId="oppo")
        try {
            client.start(scope)
            withTimeout(5_000) { while (!client.model.state.value.connected) delay(20) }
            assertTrue(client.open(thread,"course","kp",listOf("concept"),"SYNTHETIC ONLY"))
            withTimeout(5_000) { while (client.model.state.value.threads[thread]?.historyLoaded != true) delay(20) }
            assertTrue(client.model.state.value.connected)
            assertTrue(client.open(thread,"course","kp",listOf("concept"),"SYNTHETIC ONLY"),
                "Catch-up generated by opening the tutor must also preserve capability")
        } finally {
            client.close();engine.stopSuspend(0,200);actor.close();scope.cancel();root.toFile().deleteRecursively()
        }
    }

    @Test fun agentConnectionCannotSendToLegacyServer(): Unit = runBlocking {
        val received = AtomicInteger()
        val connected = CompletableDeferred<Unit>()
        val engine = embeddedServer(Netty, host="127.0.0.1", port=0) {
            install(WebSockets)
            routing { webSocketRaw("/v1/ws") {
                send(Frame.Text("""{"epoch":"legacy","lastSeq":0}"""))
                connected.complete(Unit)
                for (frame in incoming) when (frame) {
                    is Frame.Ping -> send(Frame.Pong(frame.data))
                    is Frame.Text -> received.incrementAndGet()
                    else -> Unit
                }
            } }
        }.apply { start(wait=false) }
        val scope = CoroutineScope(SupervisorJob()+Dispatchers.Default)
        val model = TutorModel(System::currentTimeMillis)
        val client = TutorClient("http://127.0.0.1:${engine.engine.resolvedConnectors().first().port}",
            "device","t".repeat(43),model,agentRunId="oppo")
        try {
            client.start(scope)
            withTimeout(5_000) { connected.await() }
            delay(300)
            assertFalse(model.state.value.connected)
            assertFalse(client.open(agentThreadId("oppo","thread"),"course","kp",emptyList(),"title"))
            assertEquals(0,received.get())
        } finally { client.close();scope.cancel();engine.stop(0,200) }
    }
}
