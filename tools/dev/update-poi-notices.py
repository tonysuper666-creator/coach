#!/usr/bin/env python3
"""Reproduce bundled POI notices from Maven Central; defaults to a dry run."""
import argparse
import io
from pathlib import Path
import urllib.request
import zipfile

COORDINATES = [
    "org.apache.poi:poi:5.5.1", "org.apache.poi:poi-ooxml:5.5.1",
    "org.apache.poi:poi-ooxml-lite:5.5.1", "org.apache.xmlbeans:xmlbeans:5.3.0",
    "commons-codec:commons-codec:1.20.0", "org.apache.commons:commons-collections4:4.5.0",
    "org.apache.commons:commons-math3:3.6.1", "commons-io:commons-io:2.21.0",
    "com.zaxxer:SparseBitSet:1.3", "org.apache.logging.log4j:log4j-api:2.24.3",
    "org.apache.commons:commons-compress:1.28.0", "org.apache.commons:commons-lang3:3.18.0",
    "com.github.virtuald:curvesapi:1.08",
]


def fetch(group, artifact, version, suffix=""):
    url = (f"https://repo.maven.apache.org/maven2/{group.replace('.', '/')}/"
           f"{artifact}/{version}/{artifact}-{version}{suffix}.jar")
    return zipfile.ZipFile(io.BytesIO(urllib.request.urlopen(url, timeout=60).read()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="replace generated notices")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / "desktopApp/src/main/resources/third-party/poi"
    files = {}
    for coordinate in COORDINATES:
        group, artifact, version = coordinate.split(":")
        archive = fetch(group, artifact, version)
        names = [name for name in archive.namelist() if name.startswith("META-INF/")
                 and name.rsplit("/", 1)[-1].upper().startswith(("LICENSE", "NOTICE"))]
        for name in names:
            files[f"{artifact}-{version}-{name.rsplit('/', 1)[-1]}"] = archive.read(name).decode("utf-8").replace("\r\n", "\n")
        if artifact == "curvesapi":
            source = fetch(group, artifact, version, "-sources")
            java = next(name for name in source.namelist() if name.endswith(".java"))
            header = source.read(java).decode().replace("\r\n", "\n").split("*/", 1)[0] + "*/\n"
            files[f"{artifact}-{version}-LICENSE"] = header
        if artifact == "SparseBitSet":
            files[f"{artifact}-{version}-LICENSE"] = files["poi-5.5.1-LICENSE"]
            files[f"{artifact}-{version}-NOTICE"] = (
                "SparseBitSet 1.3, Apache License 2.0 (artifact POM).\n"
                "This software is the work of Paladin Software International, Incorporated,\n"
                "based upon previous work done for and by Sun Microsystems, Inc.\n")
    files["README.txt"] = (
        "Apache POI slide rendering dependencies. Generated by tools/dev/update-poi-notices.py.\n"
        "All are Apache-2.0 except curvesapi (BSD-3-Clause). License/notice texts are from\n"
        "the exact Maven artifacts; curvesapi's license is its source-file header.\n"
        "SparseBitSet's POM declares Apache-2.0; attribution is from its source header.\n\n"
        + "\n".join(COORDINATES) + "\n")
    print(f"{'WRITE' if args.write else 'DRY RUN'}: {len(files)} files, {len(COORDINATES)} artifacts, {target.name}/")
    if args.write:
        target.mkdir(parents=True, exist_ok=True)
        for old in target.iterdir():
            if old.is_file():
                old.unlink()
        for name, content in files.items():
            (target / name).write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
